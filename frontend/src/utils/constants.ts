// Nuclear Decay Math Helper: A(t) = A_0 * e^(-lambda * t)
export function calculateDecay(initialActivity: number, decayConstantPerMin: number, elapsedMinutes: number): number {
  return initialActivity * Math.exp(-decayConstantPerMin * elapsedMinutes);
}

// Overshoot calculation: A_EOS = A_calib * e^(lambda * delta_t)
export function calculateEosOvershoot(targetCalibActivity: number, decayConstantPerMin: number, transitMinutes: number): number {
  return targetCalibActivity * Math.exp(decayConstantPerMin * transitMinutes);
}
